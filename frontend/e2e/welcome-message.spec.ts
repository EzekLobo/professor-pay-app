import { expect, test } from "@playwright/test";
for (const width of [320, 390, 1440]) test(`boas-vindas abre responsável sem download e preserva modelos (${width}px)`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  const privateCalls: string[] = [];
  page.on("request", request => { if (/firestore.googleapis|identitytoolkit|\/api\/kodland/.test(request.url())) privateCalls.push(request.url()); });
  await page.goto("/demo#settings");
  await page.getByRole("tab", { name: "Mensagens", exact: true }).click();
  const absence = page.getByRole("textbox", { name: "Modelo da mensagem de ausência", exact: true });
  const activity = page.getByRole("textbox", { name: "Mensagem de atividades", exact: true });
  const welcome = page.getByRole("textbox", { name: "Mensagem de boas-vindas", exact: true });
  await expect(absence).toBeVisible(); await expect(activity).toBeVisible(); await expect(welcome).toBeVisible();
  await absence.fill("Falta: {primeiro_nome}"); await activity.fill("Pendências: {aluno}: {atividades}");
  await welcome.fill("Olá {responsavel}! Boas-vindas para {aluno}, na turma {turma}. Vamos ao grupo?");
  await page.getByRole("button", { name: "Salvar mensagens", exact: true }).click();
  await expect(page.getByText("Mensagens salvas.", { exact: true })).toBeVisible();
  await page.reload(); await page.getByRole("tab", { name: "Mensagens", exact: true }).click();
  await expect(absence).toHaveValue("Falta: {primeiro_nome}"); await expect(activity).toHaveValue("Pendências: {aluno}: {atividades}");
  await expect(welcome).toHaveValue(/Boas-vindas para/);
  await page.goto("/demo#classes");
  const group = page.locator(".compact-activities-class").filter({ hasText: "Matemática particular" });
  if (await group.getAttribute("open") === null) await group.locator(":scope > summary").click();
  const shortcut = group.getByRole("button", { name: /^Dar boas-vindas ao responsável de/ }).first();
  await expect(shortcut).toBeVisible();
  await expect(shortcut).not.toHaveAttribute("download");
  const pagesBefore = page.context().pages().length;
  await shortcut.click();
  const review = page.getByRole("dialog", { name: "Boas-vindas ao responsável", exact: true });
  await expect(review).toBeVisible();
  expect(page.context().pages()).toHaveLength(pagesBefore);
  await expect(review.getByRole("textbox", { name: "WhatsApp do responsável", exact: true })).toHaveValue("5511999999999");
  const message = review.getByRole("textbox", { name: "Mensagem de boas-vindas", exact: true });
  await expect(message).toHaveValue(/Boas-vindas para Helena/);
  expect(await message.inputValue()).not.toMatch(/\{[^}]+\}/);
  await message.fill(" ");
  await expect(review.locator("a[aria-disabled]")).not.toHaveAttribute("href");
  await message.fill("Olá! Sou seu tutor. Bem-vindos à turma! Texto revisado.");
  const proceed = review.getByRole("link", { name: "Abrir conversa no WhatsApp", exact: true });
  const url = new URL((await proceed.getAttribute("href"))!);
  expect(url.hostname).toBe("wa.me"); expect(url.searchParams.get("text")).toContain("Texto revisado.");
  let downloads = 0; page.on("download", () => { downloads++; });
  await page.context().route("https://wa.me/**", route => route.fulfill({ contentType: "text/html", body: "WhatsApp de teste" }));
  const popupPromise = page.waitForEvent("popup"); await proceed.click(); const popup = await popupPromise;
  await popup.waitForLoadState(); expect(popup.url()).toBe(url.toString()); expect(downloads).toBe(0); await popup.close();
  await page.keyboard.press("Escape");
  await shortcut.click();
  await expect(message).toHaveValue(/Boas-vindas para Helena/);
  await review.getByRole("button", { name: "Cancelar", exact: true }).click();
  await expect(review).not.toBeVisible();
  const missingGroup = page.locator(".compact-activities-class").first();
  if (await missingGroup.getAttribute("open") === null) await missingGroup.locator(":scope > summary").click();
  await missingGroup.getByRole("button", { name: /^Dar boas-vindas ao responsável de/ }).first().click();
  const dialog = page.getByRole("dialog", { name: "Boas-vindas ao responsável", exact: true });
  await dialog.getByRole("textbox", { name: "WhatsApp do responsável", exact: true }).fill("123");
  await expect(dialog.locator("a[aria-disabled]")).not.toHaveAttribute("href");
  await dialog.getByRole("textbox", { name: "WhatsApp do responsável", exact: true }).fill("11912345678");
  await expect(dialog.getByRole("link", { name: "Abrir conversa no WhatsApp", exact: true })).toHaveAttribute("href", /^https:\/\/wa.me\/5511912345678\?text=/);
  await page.keyboard.press("Escape");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(privateCalls).toEqual([]);
});
