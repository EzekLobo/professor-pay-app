import { expect, test } from "@playwright/test";

for (const width of [1280, 390]) {
test(`visitante gerencia turmas e cursos no mesmo catálogo sem serviços privados (${width}px)`, async ({ page }) => {
  test.setTimeout(60_000);
  await page.setViewportSize({ width, height: 844 });
  const externalRequests: string[] = [];
  page.on("request", (request) => {
    if (/firestore\.googleapis\.com|identitytoolkit\.googleapis\.com|bo\.kodland\.org|\/api\/kodland\//.test(request.url())) externalRequests.push(request.url());
  });
  await page.goto("/demo");
  await page.getByRole("link", { name: "Turmas" }).click();
  const personalGroups = page.locator("details.manual-group-panel");
  await expect(personalGroups.getByText("Turmas autônomas", { exact: true })).toBeVisible();
  await expect(personalGroups.first()).not.toHaveAttribute("open", "");
  await personalGroups.first().locator("summary").click();
  await expect(personalGroups.getByText("Matemática particular", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Configurar grupo Turmas autônomas" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Ações da turma Matemática particular" })).toBeVisible();
  const search = page.getByRole("searchbox", { name: "Buscar grupo, turma ou aluno" });
  await search.fill("Helena");
  await expect(personalGroups.getByText("Matemática particular", { exact: true })).toBeVisible();
  await search.fill("inexistente");
  await expect(page.getByText("Nenhum grupo, turma ou aluno encontrado.")).toBeVisible();
  await search.fill("");
  await personalGroups.first().locator("summary").click();
  await page.getByRole("button", { name: "Ações da turma Matemática particular" }).click();
  await page.getByRole("menuitem", { name: "Editar turma" }).click();
  const existingClassDialog = page.getByRole("dialog", { name: "Editar turma" });
  await expect(existingClassDialog.getByRole("checkbox", { name: "Turma ativa" })).toBeChecked();
  await existingClassDialog.getByRole("button", { name: "Fechar" }).click();
  await expect(page.getByRole("heading", { name: "Turmas Kodland" })).toHaveCount(0);

  await page.getByRole("button", { name: "Adicionar turma" }).click();
  const classDialog = page.getByRole("dialog", { name: "Adicionar nova turma" });
  await classDialog.getByRole("radio", { name: "Criar novo grupo" }).check();
  await classDialog.getByLabel("Nome do grupo").fill("Reforço particular");
  await classDialog.getByLabel("Nome da turma").fill("Turma de redação");
  await classDialog.getByLabel("Tarifa da turma (R$/h)").fill("65,00");
  const date = await classDialog.getByLabel("Início").inputValue();
  const weekday = (new Date(`${date}T12:00:00Z`).getUTCDay() + 6) % 7;
  await classDialog.getByLabel("Dia da semana").selectOption(String(weekday));
  await classDialog.getByRole("button", { name: "Cadastrar aluno" }).click();
  const inlineStudent = classDialog.getByRole("group", { name: "Novo aluno" });
  await inlineStudent.getByLabel("Nome").fill("Joana Exemplo");
  await inlineStudent.getByRole("button", { name: "Salvar aluno" }).click();
  await classDialog.getByLabel("Joana Exemplo").check();
  await classDialog.getByRole("button", { name: "Salvar turma" }).click();
  await page.locator("details.manual-group-panel").filter({ has: page.getByRole("heading", { name: "Reforço particular" }) }).locator("summary").click();
  await expect(page.getByText("Turma de redação")).toBeVisible();

  if (width <= 720) await page.getByRole("button", { name: "Mais opções", exact: true }).click();
  await page.getByRole("link", { name: "Acompanhamento", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Acompanhamento" })).toBeVisible();
  await expect(page.getByRole("tab", { name: "Atividades" })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("tab", { name: "Presença" }).click();
  await expect(page.getByRole("tab", { name: "Presença" })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByLabel("Filtrar presença")).toHaveValue("ABSENT");
  await page.getByRole("button", { name: "Abrir filtros" }).click();
  await page.getByLabel("Filtrar presença").selectOption("ALL");
  await page.getByRole("button", { name: "Concluir", exact: true }).click();
  const attendanceClass = page.locator("details.attendance-class-group").first();
  await expect(attendanceClass).not.toHaveAttribute("open", "");
  await attendanceClass.locator("summary").click();
  const attendanceGrid = attendanceClass.getByLabel(/Presença da turma/);
  await expect.poll(() => attendanceGrid.evaluate((element) => element.scrollLeft)).toBeGreaterThan(0);
  const scroll = await attendanceGrid.evaluate((element) => ({ current: element.scrollLeft, max: element.scrollWidth - element.clientWidth }));
  const scrollLeft = scroll.current >= scroll.max - 1;
  await attendanceGrid.hover({ position: { x: 20, y: 10 } });
  await page.mouse.wheel(0, scrollLeft ? -300 : 300);
  if (scrollLeft) await expect.poll(() => attendanceGrid.evaluate((element) => element.scrollLeft)).toBeLessThan(scroll.current);
  else await expect.poll(() => attendanceGrid.evaluate((element) => element.scrollLeft)).toBeGreaterThan(scroll.current);
  await expect(page.getByLabel("Legenda das cores de presença").getByText("Falta sem justificativa")).toBeVisible();
  await expect(attendanceClass.locator(".attendance-column-heading strong").first()).toHaveText(/^\d{2}\/\d{2}$/);
  await expect(attendanceClass.getByText("Sem data", { exact: true })).toHaveCount(0);
  const absence = attendanceClass.getByRole("button", { name: /Enviar mensagem para/ }).first();
  await expect(absence).toBeVisible();
  await absence.click();
  const whatsAppDialog = page.getByRole("dialog", { name: "Mensagem pelo WhatsApp" });
  await expect(whatsAppDialog.getByLabel("Mensagem")).toHaveValue(/Olá, Helena! 👋\n\nSentimos sua falta na aula M\d+L\d+, em \d{2}\/\d{2}\/\d{4}\. Aconteceu alguma coisa\?\n\nSe precisar de ajuda, pode contar comigo!/s);
  await whatsAppDialog.getByLabel("Mensagem").fill("Mensagem revisada pelo professor.");
  await expect(whatsAppDialog.getByRole("link", { name: "Enviar no WhatsApp" })).toHaveAttribute("href", /Mensagem%20revisada%20pelo%20professor/);
  await whatsAppDialog.getByRole("button", { name: "Cancelar" }).click();
  await page.getByRole("tab", { name: "Atividades" }).click();
  await expect(page.getByRole("tab", { name: "Atividades" })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "Abrir filtros" }).click();
  await page.getByLabel("Organizar atividades").selectOption("student");
  await page.getByRole("button", { name: "Concluir", exact: true }).click();
  const compactView = page.getByRole("button", { name: "Compacto" });
  await expect(compactView).toHaveAttribute("aria-pressed", "false");
  await compactView.click();
  await expect(compactView).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByText("Sem pendências para os filtros atuais.")).toBeVisible();
  await page.reload();
  await expect(page.getByRole("tab", { name: "Atividades" })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByRole("button", { name: "Compacto" })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Lista" }).click();
  await expect(page.getByLabel("Organizar atividades")).toHaveValue("student");
  await page.getByRole("tab", { name: "Presença" }).click();
  await expect(page.getByLabel("Filtrar presença")).toHaveValue("ALL");

  await page.getByRole("link", { name: "Aulas" }).click();
  const courses = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Cursos" }) });
  await expect(courses.getByRole("heading", { name: "Cursos" })).toBeVisible();
  await courses.getByRole("button", { name: "Criar novo curso" }).click();
  const courseDialog = page.getByRole("dialog", { name: "Criar novo curso" });
  await courseDialog.getByLabel("Nome do curso").fill("Redação criativa");
  await courseDialog.getByLabel("Quantidade de módulos").fill("1");
  await courseDialog.getByLabel("Aulas por módulo").fill("1");
  await courseDialog.getByRole("button", { name: "Gerar estrutura" }).click();
  await courseDialog.getByLabel("Título").fill("Argumentação");
  await courseDialog.getByLabel("Atividades").fill("Redigir um parágrafo");
  await courseDialog.getByLabel("Roteiro").fill("Apresentar tese e argumentos.");
  await courseDialog.getByLabel("Slides (link)").fill("https://example.com/slides");
  await courseDialog.getByLabel("Lição de casa").fill("Revisar o texto.");
  await courseDialog.getByRole("button", { name: "Salvar curso" }).click();
  await expect(courses.getByText("Redação criativa", { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("link", { name: "Aulas" }).click();
  await expect(page.getByText("Redação criativa", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Aulas próprias", exact: true })).toHaveCount(0);
  await expect(courses.getByText("Matemática essencial", { exact: true })).toBeVisible();
  const courseCard = page.locator("details.manual-course-card").filter({ hasText: "Redação criativa" });
  await courseCard.locator("summary").click();
  await courseCard.getByRole("button", { name: "Editar curso", exact: true }).click();
  const edit = page.getByRole("dialog", { name: "Editar curso", exact: true });
  await edit.getByLabel("Nome do curso").fill("Redação revisada");
  await edit.getByLabel("Título", { exact: true }).fill("Argumentação revisada");
  await edit.getByRole("button", { name: "Salvar curso" }).click();
  await page.reload();
  await page.getByRole("link", { name: "Aulas", exact: true }).click();
  const revised = page.locator("details.manual-course-card").filter({ hasText: "Redação revisada" });
  await revised.locator("summary").click();
  await expect(revised.getByText(/Argumentação revisada/)).toBeVisible();
  await revised.getByRole("button", { name: "Excluir curso", exact: true }).click();
  await page.getByRole("dialog", { name: "Excluir curso", exact: true }).getByRole("button", { name: "Cancelar" }).click();
  await expect(revised).toBeVisible();
  await revised.getByRole("button", { name: "Excluir curso", exact: true }).click();
  await page.getByRole("button", { name: "Confirmar exclusão" }).click();
  await expect(revised).toHaveCount(0);
  await page.reload();
  await page.getByRole("link", { name: "Aulas", exact: true }).click();
  await expect(page.getByText("Redação revisada", { exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(externalRequests).toEqual([]);
});

}
