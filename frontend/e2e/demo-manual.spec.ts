import { expect, test } from "@playwright/test";

test("visitante cadastra turma, aula e correção com persistência local e sem serviços privados", async ({ page }) => {
  const externalRequests: string[] = [];
  page.on("request", (request) => {
    if (/firestore\.googleapis\.com|identitytoolkit\.googleapis\.com|bo\.kodland\.org|\/api\/kodland\//.test(request.url())) externalRequests.push(request.url());
  });
  await page.goto("/demo");
  await page.getByRole("link", { name: "Turmas" }).click();
  const personalGroups = page.locator("section.manual-group-panel");
  await expect(personalGroups.getByText("Turmas autônomas", { exact: true })).toBeVisible();
  await expect(personalGroups.getByText("Matemática particular", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Configurar grupo Turmas autônomas" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Configurar turma Matemática particular" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Excluir turma Matemática particular" })).toBeVisible();
  const search = page.getByRole("searchbox", { name: "Buscar grupo, turma ou aluno" });
  await search.fill("Helena");
  await expect(personalGroups.getByText("Matemática particular", { exact: true })).toBeVisible();
  await search.fill("inexistente");
  await expect(page.getByText("Nenhum grupo, turma ou aluno encontrado.")).toBeVisible();
  await search.fill("");
  await page.getByRole("button", { name: "Configurar turma Matemática particular" }).click();
  const existingClassDialog = page.getByRole("dialog", { name: "Editar turma" });
  await expect(existingClassDialog.getByRole("checkbox", { name: "Turma ativa" })).toBeChecked();
  await existingClassDialog.getByRole("button", { name: "Fechar" }).click();
  const kodlandPanel = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Turmas Kodland" }) });
  await kodlandPanel.locator("summary").first().click();
  await kodlandPanel.getByRole("button", { name: "Configurar grupos Kodland" }).click();
  const kodlandGroupsDialog = page.getByRole("dialog", { name: "Configurar grupos Kodland" });
  await kodlandGroupsDialog.getByRole("button", { name: /Configurar DEMO_PY_SEG-19/ }).click();
  const kodlandDialog = page.getByRole("dialog", { name: /Configurar/ });
  await kodlandDialog.getByLabel("Tarifa específica (R$/h)").fill("55,00");
  await kodlandDialog.getByLabel("Dia do recebimento").fill("20");
  await kodlandDialog.getByRole("button", { name: "Salvar configuração" }).click();
  await expect(page.getByText("Configuração da turma salva para as próximas aulas.")).toBeVisible();

  await page.getByRole("button", { name: "Adicionar turma" }).click();
  const classDialog = page.getByRole("dialog", { name: "Adicionar nova turma" });
  await classDialog.getByRole("radio", { name: "Criar novo grupo" }).check();
  await classDialog.getByLabel("Nome do grupo").fill("Reforço particular");
  await classDialog.getByLabel("Nome da turma").fill("Turma de redação");
  await classDialog.getByLabel("Tarifa da turma (R$/h)").fill("65,00");
  const date = await classDialog.getByLabel("Início").inputValue();
  const weekday = (new Date(`${date}T12:00:00Z`).getUTCDay() + 6) % 7;
  await classDialog.getByLabel("Dia da semana").selectOption(String(weekday));
  await classDialog.getByRole("button", { name: "Cadastrar aluno" }).click();
  const inlineStudent = classDialog.getByRole("group", { name: "Novo aluno" });
  await inlineStudent.getByLabel("Nome").fill("Joana Exemplo");
  await inlineStudent.getByRole("button", { name: "Salvar aluno" }).click();
  await classDialog.getByLabel("Joana Exemplo").check();
  await classDialog.getByRole("button", { name: "Salvar turma" }).click();
  await expect(page.getByText("Turma de redação")).toBeVisible();

  await page.getByRole("link", { name: "Aulas" }).click();
  const manual = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Aulas próprias" }) });
  await expect(manual.getByRole("heading", { name: "Aulas próprias" })).toBeVisible();
  await manual.locator('[data-tour="lessons-manual-class"]').selectOption({ label: "Turma de redação" });
  await manual.locator('[data-tour="lessons-manual-date"]').fill(date);
  const content = manual.locator("form").filter({ has: page.getByRole("heading", { name: "Adicionar conteúdo" }) });
  await content.getByLabel("Título").fill("Argumentação");
  await content.getByRole("button", { name: "Adicionar conteúdo" }).click();
  await expect(manual.getByText("Argumentação")).toBeVisible();
  const activity = manual.locator("form").filter({ has: page.getByRole("heading", { name: "Adicionar atividade para aluno" }) });
  await activity.getByLabel("Atividade").fill("Redigir um parágrafo");
  await activity.getByLabel("Entrega em texto").fill("Parágrafo de exemplo entregue.");
  await activity.getByRole("button", { name: "Adicionar atividade" }).click();

  await page.getByRole("link", { name: "Correções" }).click();
  await page.getByText("Turma de redação").click();
  await page.getByRole("button", { name: "Corrigir", exact: true }).click();
  const correction = page.getByRole("dialog", { name: "Corrigir atividade própria" });
  await correction.getByLabel("Feedback").fill("Bom trabalho!");
  await correction.getByRole("button", { name: "Concluir correção" }).click();
  await expect(page.getByText("Atividade corrigida.")).toBeVisible();

  await page.reload();
  await page.getByRole("link", { name: "Turmas" }).click();
  const restoredPersonalGroups = page.locator("section.manual-group-panel");
  await expect(restoredPersonalGroups.getByText("Reforço particular", { exact: true })).toBeVisible();
  await expect(restoredPersonalGroups.getByText("Turma de redação")).toBeVisible();
  await page.getByRole("link", { name: "Aulas" }).click();
  const reloadedManual = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Aulas próprias" }) });
  await reloadedManual.locator('[data-tour="lessons-manual-class"]').selectOption({ label: "Turma de redação" });
  await reloadedManual.locator('[data-tour="lessons-manual-date"]').fill(date);
  await expect(page.getByText("Argumentação")).toBeVisible();
  expect(externalRequests).toEqual([]);
});
