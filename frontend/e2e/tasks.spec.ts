import { expect, test } from "@playwright/test";

for (const width of [1440, 390, 320]) {
  test(`tarefas pessoais preservam cartões e ações no quadro em ${width}px`, async ({ page }) => {
    test.setTimeout(75_000);
    await page.setViewportSize({ width, height: 900 });
    const privateCalls: string[] = [];
    page.on("request", (request) => {
      if (/firestore\.googleapis\.com|identitytoolkit\.googleapis\.com|\/api\/kodland\//.test(request.url())) privateCalls.push(request.url());
    });
    await page.goto("/demo#tasks");
    await page.getByRole("button", { name: "Nova tarefa", exact: true }).click();
    const editor = page.getByRole("dialog", { name: "Nova tarefa", exact: true });
    await editor.getByLabel("Título", { exact: true }).fill("Resolver acesso de aluno");
    await editor.getByRole("textbox", { name: "Descrição", exact: true }).fill("Conferir o acesso antes da próxima aula.");
    await editor.getByRole("combobox", { name: "Tipo", exact: true }).selectOption("problem");
    await editor.getByRole("combobox", { name: "Prioridade", exact: true }).selectOption("urgent");
    await editor.getByLabel("Prazo", { exact: true }).fill("2026-01-10");
    await editor.getByLabel("Novo item do checklist", { exact: true }).fill("Conferir cadastro");
    await editor.getByRole("button", { name: "Adicionar item", exact: true }).click();
    await editor.getByLabel("Novo item do checklist", { exact: true }).fill("Confirmar solução");
    await editor.getByRole("button", { name: "Adicionar item", exact: true }).click();
    await editor.getByRole("button", { name: "Salvar tarefa", exact: true }).click();
    await expect(editor).not.toBeVisible();
    const title = page.getByRole("button", { name: "Resolver acesso de aluno", exact: true });
    await expect(title).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `/tmp/tasks-board-${width}.png` });
    await page.reload();
    await expect(title).toBeVisible();
    await title.click();
    const edit = page.getByRole("dialog", { name: "Editar tarefa", exact: true });
    await expect(edit.getByRole("textbox", { name: "Descrição", exact: true })).toHaveValue("Conferir o acesso antes da próxima aula.");
    await edit.getByRole("checkbox", { name: "Conferir cadastro", exact: true }).check();
    await edit.getByRole("button", { name: "Salvar tarefa", exact: true }).click();
    await page.getByRole("combobox", { name: "Mover Resolver acesso de aluno para", exact: true }).selectOption("doing");
    if (width <= 720) await page.getByRole("combobox", { name: "Etapa das tarefas", exact: true }).selectOption("doing");
    await expect(title).toBeVisible();
    await page.getByRole("combobox", { name: "Mover Resolver acesso de aluno para", exact: true }).selectOption("done");
    const complete = page.getByRole("dialog", { name: "Concluir com itens pendentes", exact: true });
    await expect(complete).toBeVisible();
    await complete.getByRole("button", { name: "Concluir mesmo assim", exact: true }).click();
    if (width <= 720) await page.getByRole("combobox", { name: "Etapa das tarefas", exact: true }).selectOption("done");
    await expect(title).toBeVisible();
    await title.click();
    await edit.getByRole("button", { name: "Arquivar", exact: true }).click();
    await expect(edit).not.toBeVisible();
    await expect(title).not.toBeVisible();
    await page.getByRole("button", { name: "Ver arquivo", exact: true }).click();
    await expect(title).toBeVisible();
    await title.click();
    await edit.getByRole("button", { name: "Restaurar", exact: true }).click();
    await expect(edit).not.toBeVisible();
    await expect(title).not.toBeVisible();
    await page.getByRole("button", { name: "Voltar ao quadro", exact: true }).click();
    await expect(title).toBeVisible();
    const search = page.getByRole("searchbox", { name: "Buscar tarefas", exact: true });
    await search.fill("inexistente");
    await expect(title).not.toBeVisible();
    await search.fill("Resolver acesso");
    await expect(title).toBeVisible();
    await title.click();
    await edit.getByRole("button", { name: "Arquivar", exact: true }).click();
    await page.getByRole("button", { name: "Ver arquivo", exact: true }).click();
    await title.click();
    await edit.getByRole("button", { name: "Excluir definitivamente", exact: true }).click();
    const deletion = page.getByRole("dialog", { name: "Excluir tarefa", exact: true });
    await expect(deletion).toBeVisible();
    await deletion.getByRole("button", { name: "Cancelar", exact: true }).click();
    await expect(title).toHaveCount(1);
    // Cancelar a exclusão conserva o cartão. A confirmação explícita o remove.
    if (!(await edit.isVisible())) await title.click();
    await edit.getByRole("button", { name: "Excluir definitivamente", exact: true }).click();
    await deletion.getByRole("button", { name: "Excluir", exact: true }).click();
    await expect(deletion).not.toBeVisible();
    await expect(title).not.toBeVisible();
    await page.reload();
    await page.getByRole("button", { name: "Ver arquivo", exact: true }).click();
    await expect(title).not.toBeVisible();
    expect(privateCalls).toEqual([]);
  });
}
